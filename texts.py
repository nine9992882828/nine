def detect_lang(tg_lang: str) -> str:
    tg_lang = (tg_lang or "").lower()
    if tg_lang.startswith("en"):
        return "en"
    if tg_lang.startswith("ar"):
        return "ar"
    if tg_lang.startswith("zh"):
        return "cn"
    return "ru"